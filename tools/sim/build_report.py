def count_scenarios() -> int:
    cache = HERE / "out" / "cache"
    return sum(1 for _ in cache.rglob("*.json")) if cache.exists() else 0


# ─── rule-derived findings ────────────────────────────────────────────────────

def derive_findings(kits: list, names: dict) -> list:
    out = []

    # 1. Harness/data integrity — a pick or mod that did not land is a content bug, not balance.
    for k in kits:
        for p in k.get("picks", []):
            if not p["applied_ok"]:
                out.append({"severity": "bug", "title": f"{k['name']}: pick '{p['name']}' was not applied",
                            "body": "UpgradeManager could not resolve this id for the kit — it cannot be offered correctly.",
                            "kit": k["id"]})
        for m in k.get("mods", {}).get("singles", []):
            if not m["active_ok"]:
                out.append({"severity": "bug", "title": f"{k['name']}: mod '{m['name']}' is not active on its own kit",
                            "body": "ProgressionManager.get_active_class_mods dropped it; the mod would do nothing when equipped.",
                            "kit": k["id"]})

    # 2. Picks that do nothing for damage, with intervals tight enough to say so. "Not
    #    significant" alone is not evidence of no effect — a wide interval is just unresolved — so
    #    the claim is an equivalence test: every offence arena's 95% interval inside ±EQUIV.
    #    Defensive picks (survive / space roles) are expected to leave damage alone and are only
    #    listed if survival was resolved as well.
    for k in kits:
        dead, unresolved_def = [], []
        for p in k.get("picks", []):
            A = p["compare"]["arenas"]
            off = [A[a] for a in ("single", "cluster", "horde") if a in A]
            if not off or not all(v["lo"] and v["hi"] and v["lo"] >= 1 - EQUIV and v["hi"] <= 1 + EQUIV
                                  for v in off):
                continue
            defensive = p.get("role") in ("survive", "space")
            pr = A.get("pressure")
            pres_tight = pr and pr["lo"] and pr["hi"] and pr["lo"] >= 1 - EQUIV and pr["hi"] <= 1 + EQUIV
            if not defensive:
                dead.append(p)
            elif pres_tight:
                dead.append(p)
            elif pr and pr["verdict"] == "flat":
                unresolved_def.append(p)
        if dead:
            out.append({"severity": "warn", "kit": k["id"],
                        "title": f"{k['name']}: {len(dead)} pick(s) that do nothing measurable for damage or clear speed",
                        "body": ", ".join(p["name"] for p in dead) + f". Every offence interval sits inside "
                                f"±{EQUIV * 100:.0f}%. For a damage or kit pick this usually means it is not "
                                "working for this kit (or only works in a situation none of the arenas create).",
                        "items": [p["id"] for p in dead]})
        if unresolved_def:
            out.append({"severity": "caveat", "kit": k["id"],
                        "title": f"{k['name']}: {len(unresolved_def)} defensive pick(s) the survival test could not resolve",
                        "body": ", ".join(p["name"] for p in unresolved_def) + ". No offence effect (expected), "
                                "and the survival interval is too wide to call. Their value is unmeasured, not zero.",
                        "items": [p["id"] for p in unresolved_def]})

    # 3. Trap picks: a pick that costs the kit at least 3% overall (shrunk estimate) with at least
    #    one arena measurably down and none measurably up. A statistically real -1% is not worth
    #    a line in a report; the threshold is practical significance, not a p-value.
    for k in kits:
        bad = [p for p in k.get("picks", [])
               if (weighted_mid(p["compare"]) or 1.0) <= 0.97
               and any(v["verdict"] == "down" for v in p["compare"]["arenas"].values())
               and not any(v["verdict"] == "up" for v in p["compare"]["arenas"].values())]
        for p in bad:
            downs = [f"{ARENA_LABEL[a]} {pct(v['ratio'])}" for a, v in p["compare"]["arenas"].items()
                     if v["verdict"] == "down"]
            out.append({"severity": "warn", "kit": k["id"],
                        "title": f"{k['name']}: '{p['name']}' is a trap pick",
                        "body": f"Measurably worse in {', '.join(downs)} and better nowhere (95% interval).",
                        "items": [p["id"]]})

    # 4. Roster outliers at level 1 — a kit far off the roster median in any arena.
    for a in ARENAS:
        vals = [(k, k["baseline"][a]["value"]) for k in kits if "baseline" in k and a in k["baseline"]
                and k["baseline"][a]["value"] is not None]
        if len(vals) < 4:
            continue
        med = sorted(v for _, v in vals)[len(vals) // 2]
        for k, v in vals:
            if med > 0 and (v / med >= 1.6 or v / med <= 0.55):
                out.append({"severity": "info", "kit": k["id"],
                            "title": f"{k['name']}: {v / med:.2f}× the roster median in {ARENA_LABEL[a]}",
                            "body": f"{fmt_val(a, v)} against a median of {fmt_val(a, med)} at level 1, no mods."})

    # 5. Class mods that do nothing on their own (equivalence, as in rule 2, over all four arenas;
    #    a mod that only matters as an evolution ingredient is still worth knowing about).
    for k in kits:
        inert = []
        for m in k.get("mods", {}).get("singles", []):
            A = m["compare"]["arenas"]
            if A and all(v["lo"] and v["hi"] and v["lo"] >= 1 - EQUIV and v["hi"] <= 1 + EQUIV
                         for a, v in A.items() if a != "pressure") \
                    and A.get("pressure", {}).get("verdict", "flat") == "flat":
                inert.append(m)
        if inert:
            out.append({"severity": "warn", "kit": k["id"],
                        "title": f"{k['name']}: {len(inert)} class mod(s) with no measurable effect alone",
                        "body": ", ".join(m["name"] for m in inert) + f". Offence within ±{EQUIV * 100:.0f}% "
                                "in every arena and survival unchanged. Check whether they need a condition "
                                "no arena creates, or only matter as an evolution ingredient.",
                        "items": [m["id"] for m in inert]})

    # 5b. Builds that crashed or hung the engine during the build search.
    for k in kits:
        for st_ in (k.get("greedy") or {}).get("steps", []):
            for c in st_.get("crashed", []):
                out.append({"severity": "bug", "kit": k["id"],
                            "title": f"{k['name']}: build crashed the engine at level {st_['step'] + 1} (candidate '{c['pick']}')",
                            "body": f"{c.get('cause', '')}. {c.get('error', '')[:400]}",
                            "items": [c["pick"]]})

    # 6. Bot-coverage caveats: a requested skill the bot never landed.
    for k in kits:
        for a, pol in k.get("policies", {}).items():
            for w in pol.get("warnings", []):
                out.append({"severity": "caveat", "kit": k["id"],
                            "title": f"{k['name']} ({ARENA_LABEL[a]}): {w}",
                            "body": "The winning policy asked for this but it never happened; that arena's number understates the kit."})
    order = {"bug": 0, "decision": 1, "fixed": 2, "warn": 3, "info": 4, "caveat": 5}
    out.sort(key=lambda f: order.get(f["severity"], 9))
    return out


## Equivalence margin for "does nothing": an effect is called absent only when the whole 95%
## interval sits within this band around zero change.
EQUIV = 0.05


def weighted_mid(c: dict):
    off, de = c.get("offense"), c.get("defense")
    if off and de:
        return math.sqrt(off * de)
    return off or de


def pct(r) -> str:
    return "-" if r is None else f"{(r - 1) * 100:+.0f}%"


ARENA_LABEL = {"single": "single-target DPS", "cluster": "pack DPS", "horde": "clear speed",
               "pressure": "survival"}


def fmt_val(a: str, v: float) -> str:
    if a == "pressure":
        return f"{v:.0f}s"
    if a == "horde":
        return f"{v:.0f} kills/min"
    return f"{v:.0f} DPS"


