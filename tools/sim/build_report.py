def load(name: str):
    p = STAGES / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def fin(x):
    return None if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))) else x


## ── Multiple comparisons ─────────────────────────────────────────────────────
## A table family (all picks of all kits, or all mod singles, or all loadouts) runs hundreds of
## per-arena tests; at a plain 95% about 1 in 40 true nulls comes out "significant". Verdicts are
## therefore Benjamini-Hochberg adjusted at a 10% false-discovery rate within each family: of the
## results coloured up/down, at most ~10% are expected to be flukes. The raw 95% interval is still
## drawn. Assigned in place as v["verdict"]; the unadjusted one is kept as v["verdict95"].
FDR_Q = 0.10


def _p_two_sided(z: float) -> float:
    return math.erfc(abs(z) / math.sqrt(2.0))


def apply_bh(compares: list[dict]) -> None:
    tests = []
    for c in compares:
        for a, v in c["arenas"].items():
            v["verdict95"] = v["verdict"]
            l, se = v.get("log"), v.get("se")
            if l is None or se is None or (isinstance(l, float) and math.isnan(l)) \
                    or (isinstance(se, float) and (math.isnan(se) or se <= 0)):
                v["verdict"] = "flat"
                continue
            tests.append((_p_two_sided(l / se), v, l))
    tests.sort(key=lambda t: t[0])
    m = len(tests)
    cut = 0
    for i, (p, _, _) in enumerate(tests, 1):
        if p <= i / m * FDR_Q:
            cut = i
    for i, (p, v, l) in enumerate(tests, 1):
        v["verdict"] = ("up" if l > 0 else "down") if i <= cut else "flat"
        v["q_rank"] = i


def slim_compare(c: dict, sh: dict | None = None, raw: bool = False) -> dict:
    """Per-arena RAW ratios + intervals (what the CI cells draw), and composite offense/defense
    from the empirical-Bayes SHRUNK estimates when the stage computed them (what the tables rank
    by — see eb_priors in sim_stages.py). Raw composites ride along for the tooltip."""
    ## raw=True for a whole-build total: the shrinkage prior was fitted to SINGLE picks, and
    ## applying it to an 8-pick build would pull a genuinely large cumulative gain toward zero.
    sh = None if raw else (sh or c.get("shrunk"))
    return {
        "arenas": {a: {k: fin(v[k]) for k in ("ratio", "lo", "hi")}
                      | {"verdict": v["verdict"], "verdict95": v.get("verdict95", v["verdict"])}
                   for a, v in c["arenas"].items()},
        "offense": fin((sh or c)["offense"]), "defense": fin((sh or c)["defense"]),
        "offense_raw": fin(c["offense"]), "defense_raw": fin(c["defense"]),
    }


def slim_summary(s: dict) -> dict:
    return {a: {"value": fin(v["value"]), "policy": v.get("policy"),
                "n": len(v.get("vals", []))} for a, v in s.items() if a in ARENAS}


def nice(name: str) -> str:
    """Evolution and character names are authored in capitals for the pixel-font UI cards; the
    report sets them in title case so a table of mixed picks reads evenly."""
    return name.title() if name.isupper() else name


def top_abilities(by: dict, n: int = 6) -> list:
    tot = sum(by.values()) or 1.0
    rows = sorted(by.items(), key=lambda kv: -kv[1])[:n]
    return [{"id": k, "share": v / tot} for k, v in rows]


